import pandas as pd
df = pd.read_csv("data/orders.csv")
df.columns = df.columns.str.strip()
print("Column Names:")
print(df.columns.tolist())
print("First 5 Rows:")
print(df.head())
print("\nColumn Names:")
print(df.columns)
print("\nData Types:")
print(df.dtypes)
print("\nDataFrame Shape:")
print(df.shape)
print("\nOrders With Quantity Greater Than 2:")
high_quantity_orders = df[df["quantity"] > 2]
print(high_quantity_orders)
df["order_value"] = df["quantity"] * df["unit_price"]
print("\nOrders With Order Value:")
print(df[["quantity", "unit_price", "order_value"]])
print("\nOrder Count By Status:")
print(df["status"].value_counts())
df["order_date"] = pd.to_datetime(df["order_date"])
print("\nOrder Dates:")
print(df["order_date"])
df["month"] = df["order_date"].dt.to_period("M")
print("\nMonth Column:")
print(df[["order_date", "month"]])
print("\nOrder Count By Month And Status:")
monthly_orders = df.groupby(["month", "status"]).size()
print(monthly_orders)
print("\nTotal Order Value By Category:")
total_by_category = df.groupby("category")["order_value"].sum()
print(total_by_category)
sorted_orders = df.sort_values(
by="order_value",
ascending=False
)
print("\nOrders Sorted By Order Value (Highest First):")
print(sorted_orders)