df_amounts = df.withColumn(
    "gross_amount",
    F.col("quantity") * F.col("unit_price")
)


df_amounts = df_amounts.withColumn(
    "discount_amount",
    F.col("gross_amount") * F.col("discount_pct") / 100
)


df_amounts = df_amounts.withColumn(
    "final_amount",
    F.col("gross_amount") - F.col("discount_amount")
)


df_amounts = df_amounts.withColumn(
    "country",
    F.lit("India")
)

df_amounts = df_amounts.withColumn(
    "high_value",
    F.when(F.col("final_amount") >= 50000, "Yes")
     .otherwise("No")
)


df_amounts.select(
    "order_id",
    "gross_amount",
    "discount_amount",
    "final_amount",
    "country",
    "high_value"
).show(10, truncate=False)

